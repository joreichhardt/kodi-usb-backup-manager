def is_german(language: str) -> bool:
    """Return whether Kodi's ISO language code identifies German."""
    return language.replace("-", "_").lower().split("_", 1)[0] == "de"


def text(language: str, key: str, **values: str) -> str:
    """Look up a UI string; English is the fallback for every non-German locale."""
    strings = STRINGS["de" if is_german(language) else "en"]
    return strings[key].format(**values)
